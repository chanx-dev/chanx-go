func TestErrors(t *testing.T) {
	for name, tc := range map[string]struct{ doc, pkg, want string }{
		"version":      {`{"asyncapi": "2.6.0", "channels": {"a": {}}}`, "x", "not 3.x"},
		"no channels":  {`{"asyncapi": "3.0.0"}`, "x", "no channels"},
		"package":      {doc, "chanx-gen", "not a Go identifier"},
		"schema clash": {strings.Replace(doc, `"Level": {`, `"KindsClient": {"type": "string"}, "Level": {`, 1), "x", "KindsClient is both"},
		"method clash": {strings.Replace(doc, `"name": "feed_topic"`, `"name": "send"`, 1), "x", "KindsClient.Send is both"},
		"unknown ref":  {strings.Replace(doc, `#/components/schemas/Level"`, `#/components/schemas/Gone"`, 1), "x", "unknown $ref"},
		"not json":     {`{`, "x", "codegen:"},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := Generate([]byte(tc.doc), Options{Package: tc.pkg})
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("got %v, want %q", err, tc.want)
			}
		})
	}
}

func TestLoad(t *testing.T) {
	dir := t.TempDir()
	yamlPath := filepath.Join(dir, "doc.yaml")
	_ = os.WriteFile(yamlPath, []byte("asyncapi: 3.0.0\nchannels:\n  a:\n    address: /a\n"), 0o644)
	got, err := Load(context.Background(), yamlPath)
	if err != nil || !strings.Contains(string(got), `"address": "/a"`) {
		t.Fatalf("%s %v", got, err)
	}
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/asyncapi.json" {
			http.NotFound(w, r)
			return
		}
		_, _ = w.Write([]byte(doc))
	}))
	defer srv.Close()
	got, err = Load(context.Background(), srv.URL+"/asyncapi.json")
	if err != nil || string(got) != doc {
		t.Fatalf("%v", err)
	}
	if _, err := Load(context.Background(), srv.URL+"/nope"); err == nil {
		t.Fatal("a 404 loaded")
	}
	if _, err := Load(context.Background(), filepath.Join(dir, "missing.json")); err == nil {
		t.Fatal("a missing file loaded")
	}
}
