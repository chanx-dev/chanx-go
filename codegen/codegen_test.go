func generate(t *testing.T, d string) map[string]string {
	t.Helper()
	files, err := Generate([]byte(d), Options{Package: "kinds"})
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for name, b := range files {
		out[name] = string(b)
	}
	return out
}

func contains(t *testing.T, src string, want ...string) {
	t.Helper()
	flat := strings.Join(strings.Fields(src), " ")
	for _, w := range want {
		if !strings.Contains(flat, strings.Join(strings.Fields(w), " ")) {
			t.Errorf("missing %q in:\n%s", w, src)
		}
	}
}

