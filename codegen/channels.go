package codegen

import (
	"bytes"
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"github.com/huynguyengl99/chanx-go/protocol"
)

func (g *generator) emitChannels(conns []conn) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by chanx-codegen. DO NOT EDIT.\n\n")
	title := g.doc.Info.Title
	if title == "" {
		title = "a chanx server"
	}
	fmt.Fprintf(&b, "// Package %s is a typed client for %s.\n", g.pkg, title)
	fmt.Fprintf(&b, "package %s\n\n", g.pkg)
	b.WriteString("import (\n\t\"context\"\n\n\tchanx \"github.com/huynguyengl99/chanx-go\"\n\tchanxclient \"github.com/huynguyengl99/chanx-go/client\"\n)\n\n")
	for _, c := range conns {
		g.emitConn(&b, c)
	}
	return b.Bytes()
}

func (g *generator) emitConn(b *bytes.Buffer, c conn) {
	fmt.Fprintf(b, "// %sChannel is %s.\n", c.name, c.ch.Address)
	fmt.Fprintf(b, "var %sChannel = chanxclient.Channel{\n\tName: %q,\n\tAddress: %q,\n\tIncoming: %s,\n}\n\n",
		c.name, c.key, c.ch.Address, g.messageList(c.flow.toClient))

	client := c.name + "Client"
	g.emitToServer(b, c.name, c.flow.toServer)

	fmt.Fprintf(b, "// %s is a connection to %s.\n", client, c.ch.Address)
	fmt.Fprintf(b, "type %s struct{ conn *chanxclient.Conn }\n\n", client)

	params := protocol.PathParams(c.ch.Address)
	var args, fill []string
	for _, p := range params {
		args = append(args, lowerName(p)+" string")
		fill = append(fill, fmt.Sprintf("%q: %s", p, lowerName(p)))
	}
	sig := "ctx context.Context, baseURL string"
	if len(args) > 0 {
		sig += ", " + strings.Join(args, ", ")
	}
	fmt.Fprintf(b, "// Dial%s connects to %s.\n", c.name, c.ch.Address)
	fmt.Fprintf(b, "func Dial%s(%s, opts ...chanxclient.Option) (*%s, error) {\n", c.name, sig, client)
	if len(fill) > 0 {
		fmt.Fprintf(b, "\topts = append(opts, chanxclient.Params(map[string]string{%s}))\n", strings.Join(fill, ", "))
	}
	fmt.Fprintf(b, "\tconn, err := chanxclient.Dial(ctx, baseURL, %sChannel, opts...)\n", c.name)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn &%s{conn}, nil\n}\n\n", client)

	fmt.Fprintf(b, "func (c *%s) Conn() *chanxclient.Conn { return c.conn }\n\n", client)
	fmt.Fprintf(b, "func (c *%s) Close() error { return c.conn.Close() }\n\n", client)
	if len(c.flow.toServer) > 0 {
		fmt.Fprintf(b, "func (c *%s) Send(ctx context.Context, m %sToServer) error { return c.conn.Send(ctx, m) }\n\n", client, c.name)
	}
	fmt.Fprintf(b, "func (c *%s) Receive(ctx context.Context) (chanx.Message, chanxclient.Envelope, error) {\n\treturn c.conn.Receive(ctx)\n}\n\n", client)
	g.emitRequests(b, "c", client, "c.conn", c.flow)

	for _, t := range c.topics {
		g.emitTopic(b, client, t)
	}
}

func (g *generator) emitToServer(b *bytes.Buffer, name string, toServer []string) {
	if len(toServer) == 0 {
		return
	}
	marker := "is" + name + "ToServer"
	fmt.Fprintf(b, "// %sToServer is a message %s accepts.\n", name, name)
	fmt.Fprintf(b, "type %sToServer interface {\n\tchanx.Message\n\t%s()\n}\n\n", name, marker)
	for _, s := range toServer {
		fmt.Fprintf(b, "func (%s) %s() {}\n", goName(s), marker)
	}
	b.WriteString("\n")
}

func (g *generator) emitRequests(b *bytes.Buffer, recv, typ, target string, f flow) {
	for _, req := range f.toServer {
		replies := f.replies[req]
		if len(replies) == 0 {
			continue
		}
		reply := "chanx.Message"
		if len(replies) == 1 {
			reply = goName(replies[0])
		}
		method := "Request" + goName(g.actionOf(req))
		fmt.Fprintf(b, "func (%s *%s) %s(ctx context.Context, m %s) (%s, error) {\n", recv, typ, method, goName(req), reply)
		fmt.Fprintf(b, "\treturn chanxclient.Reply[%s](%s.Request(ctx, m))\n}\n\n", reply, target)
	}
}

var topicParam = regexp.MustCompile(`\{(\w+)\}`)

func (g *generator) emitTopic(b *bytes.Buffer, client string, t topic) {
	pattern := t.ch.Topic.Pattern
	var args []string
	for _, m := range topicParam.FindAllStringSubmatch(pattern, -1) {
		args = append(args, lowerName(m[1])+" string")
	}
	var parts []string
	last := 0
	for _, loc := range topicParam.FindAllStringSubmatchIndex(pattern, -1) {
		if loc[0] > last {
			parts = append(parts, strconv.Quote(pattern[last:loc[0]]))
		}
		parts = append(parts, lowerName(pattern[loc[2]:loc[3]]))
		last = loc[1]
	}
	if last < len(pattern) || len(parts) == 0 {
		parts = append(parts, strconv.Quote(pattern[last:]))
	}

	method := goName(t.ch.Topic.Name)
	fmt.Fprintf(b, "// %s is the %s topic.\n", t.name, pattern)
	fmt.Fprintf(b, "type %s struct{ topic *chanxclient.Topic }\n\n", t.name)
	g.emitToServer(b, t.name, t.flow.toServer)
	fmt.Fprintf(b, "func (c *%s) %s(%s) *%s {\n", client, method, strings.Join(args, ", "), t.name)
	topicArgs := append([]string{strings.Join(parts, " + ")}, g.literals(t.flow.toClient)...)
	fmt.Fprintf(b, "\treturn &%s{c.conn.Topic(%s)}\n}\n\n", t.name, strings.Join(topicArgs, ", "))
	recv := t.name
	fmt.Fprintf(b, "func (t *%s) Topic() *chanxclient.Topic { return t.topic }\n\n", recv)
	fmt.Fprintf(b, "func (t *%s) Subscribe(ctx context.Context) error { return t.topic.Subscribe(ctx) }\n\n", recv)
	fmt.Fprintf(b, "func (t *%s) Unsubscribe(ctx context.Context) error { return t.topic.Unsubscribe(ctx) }\n\n", recv)
	if len(t.flow.toServer) > 0 {
		fmt.Fprintf(b, "func (t *%s) Send(ctx context.Context, m %sToServer) error { return t.topic.Send(ctx, m) }\n\n", recv, t.name)
	}
	fmt.Fprintf(b, "func (t *%s) Receive(ctx context.Context) (chanx.Message, chanxclient.Envelope, error) {\n\treturn t.topic.Receive(ctx)\n}\n\n", recv)
	g.emitRequests(b, "t", recv, "t.topic", t.flow)
}

func (g *generator) messageList(names []string) string {
	return "[]chanx.Message{" + strings.Join(g.literals(names), ", ") + "}"
}

func (g *generator) literals(names []string) []string {
	var items []string
	for _, n := range names {
		items = append(items, goName(n)+"{}")
	}
	return items
}

func (g *generator) actionOf(schema string) string {
	s := g.doc.Components.Schemas[schema]
	if s == nil || s.Properties.values["action"] == nil {
		return schema
	}
	action, _ := strconv.Unquote(string(s.Properties.values["action"].Const))
	return action
}
