// Package sandbox is chanx's sandbox_fastapi written with chanx-go: the
// same consumers, messages, routes and AsyncAPI document, mountable on any of
// the supported frameworks.
package sandbox

import (
	"log/slog"
	"os"
	"strings"

	chanx "github.com/huynguyengl99/chanx-go"
	"github.com/huynguyengl99/chanx-go/asyncapi"
	"github.com/huynguyengl99/chanx-go/layers"
	"github.com/huynguyengl99/chanx-go/layers/inmemory"
	"github.com/huynguyengl99/chanx-go/layers/redis"
)

// Info is the sandbox's AsyncAPI metadata.
var Info = asyncapi.Info{
	Title:       "FastAPI AsyncAPI documentation",
	Version:     "1.0.0",
	Description: "Websocket API documentation generated by Chanx",
}

// Layers returns the sandbox's layers: Redis pub/sub under the sandbox's aliases
// and prefixes when redisURL is set, in memory otherwise. There is no Redis
// queue layer yet, so "queue" and "analytics" use pub/sub.
func Layers(redisURL string) (layers.Set, error) {
	if redisURL == "" {
		chat := inmemory.New()
		return layers.Set{
			"memory": inmemory.New(), "chat": chat, "queue": inmemory.New(),
			"notifications": inmemory.New(), "analytics": inmemory.New(),
		}, nil
	}
	set := layers.Set{"memory": inmemory.New()}
	for alias, prefix := range map[string]string{"chat": "chat", "queue": "queue", "notifications": "notify", "analytics": "analytics"} {
		l, err := redis.NewPubSub(redis.PubSubOptions{Hosts: strings.Split(redisURL, ","), Prefix: prefix})
		if err != nil {
			return nil, err
		}
		set[alias] = l
	}
	return set, nil
}

// New mounts the sandbox's routes, as sandbox_fastapi/main.py.
func New(set layers.Set, logger *slog.Logger) *chanx.Engine {
	if logger == nil {
		logger = slog.Default()
	}
	e := chanx.New(chanx.Config{
		Layers:         set,
		Logger:         logger,
		SendCompletion: os.Getenv("SEND_COMPLETION") != "",
	})
	e.Handle("/ws/chat", ChatConsumer{}, chanx.Layer("chat"),
		chanx.Name("chat"), chanx.Description("Basic Chat Consumer using centralized chat layer"), chanx.Tags("chat", "showcase"))
	e.Handle("/ws/reliable", ReliableChatConsumer{}, chanx.Layer("queue"),
		chanx.Name("reliable_chat"), chanx.Description("Reliable Chat Consumer using queue-based layer"), chanx.Tags("chat", "reliable", "showcase"))
	e.Handle("/ws/notifications", NotificationConsumer{}, chanx.Layer("notifications"),
		chanx.Name("notifications"), chanx.Description("Notification Consumer for real-time notifications"), chanx.Tags("notifications", "showcase"))
	e.Handle("/ws/analytics", AnalyticsConsumer{}, chanx.Layer("analytics"),
		chanx.Name("analytics"), chanx.Description("Analytics Consumer for reliable event delivery"), chanx.Tags("analytics", "showcase"))
	e.Handle("/ws/system", SystemMessageConsumer{}, chanx.Layer("memory"),
		chanx.Name("system"), chanx.Description("System Messages Consumer - Direct WebSocket without channel layers"), chanx.Tags("system", "direct"))
	e.Handle("/ws/background_jobs", BackgroundJobConsumer{}, chanx.Layer("chat"),
		chanx.Name("background_jobs"), chanx.Description("Background Jobs Consumer - Real background job processing with ARQ"), chanx.Tags("jobs", "background", "arq"))
	e.Handle("/ws/room/{room_name}", RoomChatConsumer{}, chanx.Layer("chat"),
		chanx.Name("room_chat"), chanx.Description("Room Chat Consumer - Dynamic room-based messaging"), chanx.Tags("chat", "rooms"))
	e.Handle("/ws/topics", TopicHubConsumer{}, chanx.Layer("chat"),
		chanx.Name("topic_hub"), chanx.Description("Several topics multiplexed over a single connection"), chanx.Tags("topics"))
	e.Handle("/ws/topics/room/{room_name}", chanx.TopicConsumer(&RoomTopic{}))
	return e
}
